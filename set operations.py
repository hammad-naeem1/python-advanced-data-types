# 3.                      (Difference)

# • Definition: Returns elements that are in the first set but not in the second set.
# • Operator: -
# • Method: setA.difference(setB)


# # Example
# set_a = {1, 2, 3}
# set_b = {3, 4, 5}

# # Elements in set_a but not in set_b
# result_op = set_a - set_b  # {1, 2}

# # Using method
# result_meth = set_a.difference(set_b)  # {1, 2}
