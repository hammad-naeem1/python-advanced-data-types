# 1.                       ( Union)

# • Definition: Combines all unique elements from both sets.
# • Operator: |
# • Method: setA.union(setB)

# # Example
# set_a = {1, 2, 3}
# set_b = {3, 4, 5}


# 2.                    (Intersection)

# • Definition: Keeps only the elements that exist in both sets.
# • Operator: &
# • Method: setA.intersection(setB)
# # Example
# set_a = {1, 2, 3}
# # Using operator
# result_op = set_a | set_b  # {1, 2, 3, 4, 5}

# # Using method
# result_meth = set_a.union(set_b)  # {1, 2, 3, 4, 5}



